/** Translate canonical English checklist/label text for display. */
function tr(text) {
  if (currentLang === "en" || !text) return text;
  const d = TEXT[currentLang];
  return (d && d[text]) || text;
}

/* ==================================================================
   Pluralized nouns used inside UI templates (issue counts, photo
   counts, and so on). Spanish/Portuguese pluralization is regular
   enough here that a two-form table per word is all we need.
   ================================================================== */
const PLURALS = {
  issue: { en: ["issue", "issues"], es: ["problema", "problemas"], pt: ["problema", "problemas"] },
  photo: { en: ["photo", "photos"], es: ["foto", "fotos"], pt: ["foto", "fotos"] },
  item: { en: ["item", "items"], es: ["ítem", "ítems"], pt: ["item", "itens"] },
  audit: { en: ["audit", "audits"], es: ["auditoría", "auditorías"], pt: ["auditoria", "auditorias"] },
};
function noun(key, n) {
  const table = PLURALS[key] || PLURALS.issue;
  const forms = table[currentLang] || table.en;
  return n === 1 ? forms[0] : forms[1];
}

