/** UI string lookup with {{placeholder}} substitution. Falls back to
 *  English, then to the raw key, so a missing translation never breaks
 *  rendering. */
function ui(key, vars) {
  const d = UI_STRINGS[currentLang] || UI_STRINGS.en;
  let s = (d && d[key]) || UI_STRINGS.en[key] || key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = s.split("{{" + k + "}}").join(String(vars[k]));
    });
  }
  return s;
}

